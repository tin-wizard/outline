import { useTranslation } from "react-i18next";
import Flex from "~/components/Flex";
import Input from "~/components/Input";
import Switch from "~/components/Switch";
import Text from "~/components/Text";
import {
  CUSTOM_CODE_MAX_LENGTH,
  CUSTOM_CODE_MIN_LENGTH,
} from "../../shared/accessCode";
import type { AccessCodeChoice } from "../accessCodeForm";
import { accessCodeChoiceProblem } from "../accessCodeForm";

interface Props {
  /** The current choice. The typed code lives only in the caller's state. */
  value: AccessCodeChoice;
  /** Called with the whole new choice on every change. */
  onChange: (value: AccessCodeChoice) => void;
  disabled?: boolean;
}

/**
 * Chooses how a new access code is issued: generated by the server and shown
 * once, or set by the administrator and typed twice.
 */
export function AccessCodeFields({ value, onChange, disabled }: Props) {
  const { t } = useTranslation();
  const problem = accessCodeChoiceProblem(value);

  const codeError =
    value.code.length === 0
      ? undefined
      : problem === "length"
        ? t("Use {{ min }} to {{ max }} characters, not counting spaces.", {
            min: CUSTOM_CODE_MIN_LENGTH,
            max: CUSTOM_CODE_MAX_LENGTH,
          })
        : problem === "characters"
          ? t("Use letters, digits and punctuation only.")
          : undefined;
  const confirmError =
    problem === "mismatch" ? t("The access codes do not match.") : undefined;

  return (
    <Flex column gap={8}>
      <Switch
        label={t("Set my own access code")}
        note={
          value.custom
            ? t(
                "Readers type this code to open the site. Codes are not case-sensitive and spaces are ignored."
              )
            : t("A code is generated and shown to you once after publishing.")
        }
        checked={value.custom}
        onChange={(custom: boolean) =>
          onChange({ custom, code: "", confirm: "" })
        }
        disabled={disabled}
      />
      {value.custom && (
        <>
          <Input
            type="password"
            label={t("Access code")}
            value={value.code}
            onChange={(ev) => onChange({ ...value, code: ev.target.value })}
            error={codeError}
            autoComplete="new-password"
            maxLength={256}
            disabled={disabled}
            required
          />
          <Input
            type="password"
            label={t("Confirm access code")}
            value={value.confirm}
            onChange={(ev) => onChange({ ...value, confirm: ev.target.value })}
            error={confirmError}
            autoComplete="new-password"
            maxLength={256}
            disabled={disabled}
            required
          />
          <Text as="p" type="tertiary" size="small">
            {t(
              "At least {{ min }} characters. Anyone with the code can read the site, so choose one that is hard to guess.",
              { min: CUSTOM_CODE_MIN_LENGTH }
            )}
          </Text>
        </>
      )}
    </Flex>
  );
}
