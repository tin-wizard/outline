import { z } from "zod";
import { BaseSchema } from "@server/routes/api/schema";
import {
  CUSTOM_CODE_MAX_LENGTH,
  CUSTOM_CODE_MIN_LENGTH,
  PagesGateType,
  customCodeProblem,
} from "../../shared/accessCode";
import { validateHostname } from "../lib/hostnames";
import { isValidPageKey } from "../lib/keys";

export const PagesListSchema = BaseSchema.extend({
  body: z.object({
    /** Filters sites by title or slug. */
    query: z.string().optional(),
  }),
});

export type PagesListReq = z.infer<typeof PagesListSchema>;

export const PagesInfoSchema = BaseSchema.extend({
  body: z.object({
    id: z.uuid(),
  }),
});

export type PagesInfoReq = z.infer<typeof PagesInfoSchema>;

export const PagesCreateSchema = BaseSchema.extend({
  body: z.object({
    /** Checked with assertValidSlug in the route for a precise message. */
    slug: z.string(),
    title: z.string().trim().min(1).max(255),
    measurementEnabled: z.boolean().optional(),
    /** Checked with validateHostname in the route. */
    hostname: z.string().optional(),
    /** "code" (the default) protects every page; "none" publishes plain pages. */
    gateType: z.enum(PagesGateType).optional(),
  }),
});

export type PagesCreateReq = z.infer<typeof PagesCreateSchema>;

// Unknown keys (slug, status, prefix, codeVersion...) are stripped by zod.
export const PagesUpdateSchema = BaseSchema.extend({
  body: z.object({
    id: z.uuid(),
    title: z.string().trim().min(1).max(255).optional(),
    measurementEnabled: z.boolean().optional(),
  }),
});

export type PagesUpdateReq = z.infer<typeof PagesUpdateSchema>;

export const PagesInsightsSchema = BaseSchema.extend({
  body: z.object({
    id: z.uuid(),
    period: z.enum(["day", "week"]).default("day"),
    /** The range in days; weeks round up to whole weeks. */
    days: z.union([z.literal(7), z.literal(30), z.literal(90)]).default(30),
  }),
});

export type PagesInsightsReq = z.infer<typeof PagesInsightsSchema>;

/**
 * An access code chosen by the administrator, set when a new code is issued.
 * Secret: never log or echo it. The message does not include the value.
 */
const newAccessCode = z
  .string()
  .max(256)
  .refine((code) => !customCodeProblem(code), {
    message: `The access code must be ${CUSTOM_CODE_MIN_LENGTH} to ${CUSTOM_CODE_MAX_LENGTH} characters, ignoring spaces, using letters, digits and punctuation only`,
  })
  .optional();

/** Omitted on republish or rotation to reuse the sources already published. */
const sources = z
  .array(
    z.object({
      type: z.enum(["document", "collection"]),
      id: z.uuid(),
    })
  )
  .min(1)
  .max(20)
  .optional();

export const PagesPublishSchema = BaseSchema.extend({
  body: z.object({
    id: z.uuid(),
    sources,
    /** Secret: never log or echo it. Zod messages do not include the value. */
    accessCode: z.string().max(64).optional(),
    /** Only on the first publish of a protected site; replaces the generated code. */
    newAccessCode,
  }),
});

export type PagesPublishReq = z.infer<typeof PagesPublishSchema>;

// No current access code: rotation replaces it and verifies nothing. Zod
// strips one.
export const PagesRotateSchema = BaseSchema.extend({
  body: z.object({
    id: z.uuid(),
    sources,
    /** Replaces the generated code. */
    newAccessCode,
  }),
});

export type PagesRotateReq = z.infer<typeof PagesRotateSchema>;

export const PagesUnpublishSchema = PagesInfoSchema;

export type PagesUnpublishReq = z.infer<typeof PagesUnpublishSchema>;

export const PagesDeleteSchema = PagesInfoSchema;

export type PagesDeleteReq = z.infer<typeof PagesDeleteSchema>;

/** True for a bare, lowercase, public hostname, the only referrer stored. */
function isReferrerHost(value: string): boolean {
  try {
    return validateHostname(value, []) === value;
  } catch {
    return false;
  }
}

/**
 * One measurement event from a published page. Parsed from the raw body by
 * the ingest route, not by validate(); unknown keys are stripped.
 */
export const PagesIngestEventSchema = z.object({
  /** The site's ingest key. */
  k: z.string().regex(/^[A-Za-z0-9_-]{22,64}$/),
  /** The page key within the site. */
  p: z.string().max(1024).refine(isValidPageKey),
  /** A random id per visitor tab session, generated by the beacon. */
  s: z.string().regex(/^[a-z0-9]{16,32}$/),
  /** Client clock epoch seconds of the page load; clamped by the route. */
  st: z.number().int().min(0),
  t: z.enum(["view", "beat", "end"]),
  /** Cumulative active seconds on this page view. */
  a: z.number().int().min(0).max(28800),
  /** The referrer's host only. */
  r: z.string().max(253).refine(isReferrerHost).optional(),
});

export type PagesIngestEvent = z.infer<typeof PagesIngestEventSchema>;

export const PagesPublishArtifactSchema = BaseSchema.extend({
  body: z.object({
    documentId: z.uuid(),
    attachmentId: z.uuid(),
    title: z.string().trim().min(1).max(255).optional(),
    /** Checked with assertValidSlug in the route; a random one is generated when omitted. */
    slug: z.string().optional(),
  }),
});

export type PagesPublishArtifactReq = z.infer<
  typeof PagesPublishArtifactSchema
>;
