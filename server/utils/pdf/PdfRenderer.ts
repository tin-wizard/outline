import { chromium } from "playwright-core";
import env from "@server/env";
import { InternalError } from "@server/errors";
import Logger from "@server/logging/Logger";
import { escapeHtml } from "./PrintDocument";
import { pageDimensions } from "./printStyles";
import type { PrintOptions } from "./types";

/** Maximum number of browsers rendering at the same time. */
const maxConcurrency = 2;

/** Time allowed for a document to load before rendering is abandoned. */
const renderTimeout = 60 * 1000;

/**
 * Stylesheet host that KaTeX formulas depend on, the only remote resource a
 * document is allowed to load.
 */
const allowedRemotePrefix = "https://cdn.jsdelivr.net/npm/katex@";

/**
 * Renders HTML to PDF using a headless Chromium browser.
 */
export default class PdfRenderer {
  /**
   * Renders an HTML document to a PDF.
   *
   * @param html the full HTML document to render.
   * @param options layout options for the output.
   * @returns the PDF file contents.
   * @throws if the browser cannot be started or the render fails.
   */
  public static async render(
    html: string,
    options: PrintOptions = {}
  ): Promise<Buffer> {
    await PdfRenderer.acquire();

    try {
      return await PdfRenderer.renderWithBrowser(html, options);
    } finally {
      PdfRenderer.release();
    }
  }

  private static active = 0;

  private static waiting: (() => void)[] = [];

  private static async renderWithBrowser(html: string, options: PrintOptions) {
    const size = pageDimensions[options.pageSize ?? "Letter"];
    const browser = await chromium
      .launch({
        executablePath: env.PDF_EXPORT_CHROMIUM_PATH,
        // The content rendered is generated by the server from the document
        // schema and has network access removed, so the sandbox, which cannot
        // run in most containers, is not relied upon.
        args: ["--no-sandbox", "--disable-dev-shm-usage"],
      })
      .catch((err) => {
        Logger.error("Failed to start the browser for PDF export", err);
        throw InternalError(
          "PDF export is not available, the browser could not be started"
        );
      });

    try {
      const context = await browser.newContext();

      // Documents can reference arbitrary URLs. Block everything except inline
      // data so that rendering cannot be used to reach internal services.
      await context.route("**/*", (route) => {
        const url = route.request().url();
        if (url.startsWith("data:") || url.startsWith(allowedRemotePrefix)) {
          return route.continue();
        }
        return route.abort();
      });

      const page = await context.newPage();
      await page.setContent(html, {
        waitUntil: "load",
        timeout: renderTimeout,
      });
      await page.evaluate(() => document.fonts.ready);

      const headerTitle = options.headerTitle
        ? escapeHtml(options.headerTitle)
        : "";
      const textStyle =
        "font-family: Arial, 'Liberation Sans', sans-serif; font-size: 8px; color: #666; width: 100%; padding: 0 0.9in;";

      const pdf = await page.pdf({
        width: `${size.width}in`,
        height: `${size.height}in`,
        margin: { top: "1in", bottom: "1in", left: "0.9in", right: "0.9in" },
        printBackground: true,
        displayHeaderFooter: true,
        headerTemplate: `<div style="${textStyle} text-align: left;">${headerTitle}</div>`,
        footerTemplate: `<div style="${textStyle} text-align: center;"><span class="pageNumber"></span> / <span class="totalPages"></span></div>`,
      });

      return Buffer.from(pdf);
    } finally {
      await browser.close().catch((err) => {
        Logger.warn("Failed to close the PDF export browser", err);
      });
    }
  }

  private static async acquire() {
    if (PdfRenderer.active < maxConcurrency) {
      PdfRenderer.active++;
      return;
    }
    await new Promise<void>((resolve) => PdfRenderer.waiting.push(resolve));
  }

  private static release() {
    const next = PdfRenderer.waiting.shift();
    if (next) {
      // The slot is handed directly to the next waiting render.
      next();
      return;
    }
    PdfRenderer.active--;
  }
}
